import { useState } from 'react';
import { generateAiDescription } from '../api';

/**
 * Task Creation Form Component (Practical 13: AI API Integration)
 * Posts new task data to backend /tasks endpoint
 * Includes AI description generation with loading state, editable suggestion,
 * and responsible AI disclaimer banner.
 */
function TaskForm({ onTaskCreated, isSubmitting }) {
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [priority, setPriority] = useState('medium');
  const [validationError, setValidationError] = useState('');

  // Practical 13: AI Suggestion state
  const [isGeneratingAi, setIsGeneratingAi] = useState(false);
  const [aiNotice, setAiNotice] = useState(null);

  const handleGenerateAi = async () => {
    if (!title.trim()) {
      setValidationError('Please enter a task title first so AI can suggest a relevant description.');
      return;
    }
    setValidationError('');
    setIsGeneratingAi(true);
    setAiNotice(null);

    try {
      const res = await generateAiDescription(title.trim());
      if (res.success && res.description) {
        setDescription(res.description);
        if (res.suggestedPriority) {
          setPriority(res.suggestedPriority);
        }
        setAiNotice({
          source: res.source || 'AI Assistant',
          disclaimer: res.disclaimer || 'This suggestion was generated by AI. Please review and modify before saving.',
          isFallback: res.isFallback || false
        });
      } else if (res.error) {
        setValidationError(res.error);
      }
    } catch (err) {
      setValidationError('Failed to generate AI suggestion: ' + err.message);
    } finally {
      setIsGeneratingAi(false);
    }
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!title.trim()) {
      setValidationError('Task title is required.');
      return;
    }
    setValidationError('');

    const taskData = {
      title: title.trim(),
      description: description.trim(),
      priority,
      completed: false
    };

    const success = await onTaskCreated(taskData);
    if (success) {
      setTitle('');
      setDescription('');
      setPriority('medium');
      setAiNotice(null);
    }
  };

  return (
    <div className="card task-form-card">
      <div className="form-header">
        <h3>Create New Task</h3>
        <span className="form-subtext">Persists directly into MongoDB via Express backend</span>
      </div>

      {validationError && (
        <div className="client-validation-error">
          <span>⚠️ {validationError}</span>
        </div>
      )}

      {/* Supplementary Problem 3: Visible Responsible AI Disclaimer Banner */}
      {aiNotice && (
        <div style={{
          background: 'rgba(59, 130, 246, 0.1)',
          border: '1px solid rgba(59, 130, 246, 0.3)',
          borderRadius: '8px',
          padding: '10px 14px',
          marginBottom: '14px',
          fontSize: '0.85rem',
          color: '#2563eb'
        }}>
          <strong>🤖 AI Suggestion Applied ({aiNotice.source}):</strong>
          <p style={{ margin: '4px 0 0', color: '#4b5563', fontSize: '0.8rem' }}>
            {aiNotice.disclaimer}
          </p>
        </div>
      )}

      <form onSubmit={handleSubmit} className="task-form">
        <div className="form-row">
          <div className="form-group flex-3">
            <label htmlFor="task-title">Task Title *</label>
            <input
              type="text"
              id="task-title"
              className="form-control"
              placeholder="e.g. Implement OAuth2 Google Login in Express"
              value={title}
              onChange={(e) => setTitle(e.target.value)}
              disabled={isSubmitting || isGeneratingAi}
              required
            />
          </div>

          <div className="form-group flex-1">
            <label htmlFor="task-priority">Priority</label>
            <select
              id="task-priority"
              className="form-control"
              value={priority}
              onChange={(e) => setPriority(e.target.value)}
              disabled={isSubmitting || isGeneratingAi}
            >
              <option value="low">Low</option>
              <option value="medium">Medium</option>
              <option value="high">High</option>
            </select>
          </div>
        </div>

        <div className="form-group">
          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
            <label htmlFor="task-desc" style={{ marginBottom: 0 }}>Description (Optional)</label>
            {/* Practical 13: Generate Description AI Button with Loading State */}
            <button
              type="button"
              onClick={handleGenerateAi}
              disabled={isGeneratingAi || isSubmitting || !title.trim()}
              style={{
                background: isGeneratingAi ? '#9ca3af' : 'linear-gradient(135deg, #6366f1, #8b5cf6)',
                color: 'white',
                border: 'none',
                borderRadius: '6px',
                padding: '4px 10px',
                fontSize: '0.78rem',
                fontWeight: 600,
                cursor: (isGeneratingAi || !title.trim()) ? 'not-allowed' : 'pointer',
                display: 'inline-flex',
                alignItems: 'center',
                gap: '6px',
                transition: 'all 0.2s ease'
              }}
              title="Auto-generate an intelligent task description based on the title"
            >
              {isGeneratingAi ? (
                <>
                  <span className="btn-spinner" style={{ width: '12px', height: '12px' }}></span>
                  Generating with AI...
                </>
              ) : (
                '✨ AI Generate Description'
              )}
            </button>
          </div>

          <textarea
            id="task-desc"
            className="form-control"
            rows={4}
            placeholder="Additional notes, specifications, or click 'AI Generate Description' above..."
            value={description}
            onChange={(e) => setDescription(e.target.value)}
            disabled={isSubmitting || isGeneratingAi}
          />
        </div>

        <div className="form-actions">
          <button
            type="submit"
            className="btn btn-primary submit-task-btn"
            disabled={isSubmitting || isGeneratingAi || !title.trim()}
          >
            {isSubmitting ? (
              <>
                <span className="btn-spinner"></span> Creating Task...
              </>
            ) : (
              '+ Add Task to MongoDB'
            )}
          </button>
        </div>
      </form>
    </div>
  );
}

export default TaskForm;
